const collator = new Intl.Collator('ru');

export const GLOSSARY_TERMS = [...TERMS].sort((left, right) => collator.compare(left.term, right.term));

const TERMS_BY_ID = new Map(GLOSSARY_TERMS.map((term) => [term.id, term]));

export function glossaryTerm(id) {
  return TERMS_BY_ID.get(id) ?? null;
}

export function glossaryTopic(key) {
  return GLOSSARY_TOPICS.find((topic) => topic.key === key) ?? null;
}

// Alphabetical; `topic` null means every term.
export function glossaryTerms(topic = null) {
  return topic ? GLOSSARY_TERMS.filter((term) => term.topic === topic) : GLOSSARY_TERMS;
}

// Ё files under Е, as in paper dictionaries.
export function glossaryLetter(term) {
  const letter = term.term.charAt(0).toLocaleUpperCase('ru');
  return letter === 'Ё' ? 'Е' : letter;
}

export function glossaryLetterGroups(terms) {
  const groups = [];
  for (const term of terms) {
    const letter = glossaryLetter(term);
    if (groups.at(-1)?.letter !== letter) groups.push({ letter, terms: [] });
    groups.at(-1).terms.push(term);
  }
  return groups;
}
